import assert from "node:assert/strict";
import { WorkspaceHistory, normalizeAppearance, legendLayout, cleanSnapshot, parseComparisonFrequencies, comparisonRows, comparisonCsv } from "../src/workspaceTools.js";
import { interpolate } from "../src/audioMath.js";
const history = new WorkspaceHistory(4);
const original = { curves: [{ id: "a", data: [{ frequency: 20, level: 70 }] }], offset: 0 };
history.record(original); original.offset = 2; history.record(original);
history.record({ curves: [], offset: 2 });
assert.equal(history.undo().curves[0].id, "a"); assert.equal(history.undo().offset, 0);
assert.equal(history.redo().offset, 2);
history.record({ curves: [], offset: 3 }); assert.equal(history.canRedo, false);
assert.equal(history.record({ curves: [], offset: 3 }), false);
for (let i = 0; i < 10; i++) history.record({ i }); assert.equal(history.entries.length, 4);
const budget = new WorkspaceHistory(50, 100); for (let i = 0; i < 10; i++) budget.record({ value: "1234567890", i }); assert(budget.entries.length < 4);
assert.deepEqual(cleanSnapshot({ data: [1], smoothingCache: [2], nested: { displayCache: 3, name: "a" } }), { data: [1], nested: { name: "a" } });
assert.equal(normalizeAppearance({ axisFontSize: 999 }).axisFontSize, 28);
assert.equal(normalizeAppearance({ axisColor: "red" }).axisColor, "#657484");
assert.deepEqual(normalizeAppearance({ legendCustomPosition: { x: -2, y: 3 } }).legendCustomPosition, { x: 0, y: 1 });
const layout = legendLayout([{ label: "abc" }, { label: "123456" }, { label: "a" }], text => text.length * 10, { columns: 2, rowHeight: 24, lineLength: 30, gap: 8 });
assert.equal(layout.width, 190); assert.equal(layout.height, 48);
assert.deepEqual(layout.positions[2], { x: 0, y: 24 });
assert.deepEqual(parseComparisonFrequencies("1000，20 1000;60"), [20, 60, 1000]);
assert.throws(() => parseComparisonFrequencies("10,1000"));
assert.throws(() => parseComparisonFrequencies("bad"));
const rows = comparisonRows([{ name: '耳机"A', data: [{ frequency: 100, level: 70 }, { frequency: 1000, level: 80 }] }], [20, 100, 1000, 2000], interpolate);
assert.deepEqual(rows[0].values, [null, 70, 80, null]);
const csv = comparisonCsv(rows, [20, 100, 1000, 2000]); assert(csv.startsWith("\ufeff")); assert(csv.includes('"耳机""A"')); assert(csv.includes('"70.00"'));
console.log("PASS: history deletion recovery/redo/branching/memory limits; normalized appearance; column geometry; frequency validation; missing-data and CSV escaping.");
